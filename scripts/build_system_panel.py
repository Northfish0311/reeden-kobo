#!/usr/bin/env python3
"""Generate fixed-size e-ink labels from the bundled OFL font, without book data."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
labels = {
    'title': ('设备控制', 38), 'wifi': ('Wi-Fi', 32), 'cover': ('合盖休眠', 32),
    'unknown': ('状态待确认', 25), 'off': ('已关闭', 25), 'on': ('已开启，未连接', 25),
    'connected': ('已连接', 25), 'busy': ('正在处理…', 25), 'error': ('操作失败，可刷新重试', 25),
    'enabled': ('已开启', 25), 'unsupported': ('传感器暂不支持', 25),
    'disabled': ('已停用', 25), 'refresh': ('刷新', 26), 'lock': ('立即锁屏', 28),
    'back': ('返回阅读', 28),
}
out = ['/* Generated by scripts/build_system_panel.py. Bundled font: SIL OFL. */',
       '#pragma once', '#include <stdint.h>',
       'typedef struct { unsigned width,height; const uint8_t *bits; } PanelLabel;']
for name, (text, size) in labels.items():
    font = ImageFont.truetype(str(ROOT / 'prebuilt/fonts/KoboCJKMath-Regular.ttf'), size)
    left, top, right, bottom = font.getbbox(text)
    image = Image.new('L', (right-left, bottom-top), 255)
    ImageDraw.Draw(image).text((-left, -top), text, font=font, fill=0)
    pixels = [int(n < 160) for n in image.getdata()]
    data = [sum(pixels[j] << (7-(j-i)) for j in range(i, min(i+8, len(pixels))))
            for i in range(0, len(pixels), 8)]
    out.append(f'static const uint8_t panel_{name}_bits[]={{' + ','.join(map(str, data)) + '};')
    out.append(f'static const PanelLabel panel_{name}={{{image.width},{image.height},panel_{name}_bits}};')
(ROOT / 'src/system_panel_art.h').write_text('\n'.join(out)+'\n', encoding='ascii')
print('Generated system panel labels from the bundled font')
